-- Adds push_subscriptions, backing Web Push notifications
-- (lua/src/webpush.lua + lua/src/routes.lua's M.push_* functions). One row
-- per browser/device a user has enabled push on -- endpoint/p256dh/auth
-- are exactly the three fields a PushSubscription object gives the
-- frontend (JSON.stringify(subscription) on the browser side already
-- nests p256dh/auth under a "keys" object; the backend just flattens them
-- into columns). UNIQUE on endpoint, not (user_id, endpoint): a given
-- browser subscription URL is inherently one-per-device already, and
-- re-subscribing (e.g. after clearing site data) lands a fresh endpoint
-- rather than reusing the old one, so this never needs a multi-user
-- conflict policy.
--
-- Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS push_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  endpoint TEXT NOT NULL UNIQUE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  user_agent VARCHAR(300),
  created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user ON push_subscriptions(user_id);
