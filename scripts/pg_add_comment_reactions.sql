-- Adds media_comment_reactions, backing per-comment emoji reactions
-- (lua/src/routes.lua's M.react_to_comment_route) -- the same one-emoji-
-- per-user toggle media_reactions already does for whole posts, just keyed
-- by comment_id instead of media_id. Mirrors that table's shape exactly
-- (same column set, same unique-per-user constraint, same ON DELETE
-- CASCADE semantics) rather than inventing a new shape for what is
-- otherwise an identical feature one level down.
--
-- Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS media_comment_reactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id BIGINT NOT NULL REFERENCES media_comments(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  emoji VARCHAR(16) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  UNIQUE (comment_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_comment_reactions_comment ON media_comment_reactions(comment_id);
CREATE INDEX IF NOT EXISTS idx_comment_reactions_user ON media_comment_reactions(user_id);
