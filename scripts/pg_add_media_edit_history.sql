-- Adds media_edit_history, backing the per-post edit history feature
-- (lua/src/routes.lua's perform_update_media writes rows here, M.media_edit_history
-- reads them back). One row per PATCH /api/media/:id that actually changed
-- something -- perform_update_media diffs old vs. new field values first and
-- skips the insert entirely on a no-op save, so this never fills up with
-- noise rows for unedited re-saves.
--
-- `changes` is a JSON object keyed by field name, each value a {from, to}
-- pair -- just the fields that changed in that one edit, not a full
-- before/after snapshot of the post.
--
-- Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS media_edit_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  media_id BIGINT NOT NULL REFERENCES media_items(id) ON DELETE CASCADE,
  editor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  changes JSONB NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_media_edit_history_media ON media_edit_history(media_id, created_at DESC);
