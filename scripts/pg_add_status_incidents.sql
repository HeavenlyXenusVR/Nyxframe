-- Adds status_incidents, backing the public uptime/status page
-- (lua/src/routes.lua's M.public_status / M.admin_create_incident /
-- M.admin_resolve_incident). Separate from telemetry_events (which already
-- records job/request outcomes) because an incident is a human-curated
-- statement ("we know about this, here's what happened"), not a raw event
-- stream -- the status page shows this table's rows plus a live health
-- check, not a dump of telemetry.
--
-- Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS status_incidents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  severity VARCHAR(20) NOT NULL DEFAULT 'minor',
  started_at TIMESTAMP NOT NULL DEFAULT now(),
  resolved_at TIMESTAMP,
  created_by BIGINT REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_status_incidents_started ON status_incidents(started_at DESC);
